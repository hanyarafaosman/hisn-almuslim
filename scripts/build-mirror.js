// Builds the backup copy of the outside files the app cannot ship itself: adhkar audio (hisnmuslim.com)
// and printed-Mushaf page fonts (static.qurancdn.com). The output folder is the hisn-almuslim-assets
// repository, served by GitHub Pages at the address in www/js/mirror.js; files keep their source path.
// Usage: node scripts/build-mirror.js <clone of hisn-almuslim-assets>   (then commit and push there)
// Files already present with the source size are kept, so a rerun only downloads what changed.
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const WWW = path.join(__dirname, "..", "www");
const readJson = f => JSON.parse(fs.readFileSync(path.join(WWW, f), "utf8"));
// js/mirror.js is a browser module; load it as one (a data: URL avoids Node's "typeless package" warning).
const loadMirror = () => import("data:text/javascript," + encodeURIComponent(fs.readFileSync(path.join(WWW, "js", "mirror.js"), "utf8")));
module.exports = { loadMirror };

async function get(url, method = "GET") {
  let last;
  for (let i = 0; i < 4; i++) {
    try { const r = await fetch(url, { method }); if (r.ok) return r; last = new Error("HTTP " + r.status); if (r.status === 404) break; }
    catch (e) { last = e; }
    await new Promise(r => setTimeout(r, 1500 * (i + 1)));
  }
  throw new Error(`${url}: ${last.message}`);
}

if (require.main === module) (async () => {
  const out = process.argv[2];
  if (!out || !fs.existsSync(out)) { console.error("usage: node scripts/build-mirror.js <folder>"); process.exit(1); }
  const { MIRROR, mirrorOf } = await loadMirror();
  const db = readJson("data/hisn.json"), { fonts } = readJson("mushaf/madinah.json");
  const groups = {
    audio: [...new Set([...db.categories.map(c => c.audio), ...db.categories.flatMap(c => c.items.map(i => i.audio))].filter(Boolean))],
    ...Object.fromEntries(Object.entries(fonts).map(([v, f]) => [`pages-${v}`, Array.from({ length: 604 }, (_, i) => f.url.replace("{n}", i + 1))])),
  };
  const files = {}; let fetched = 0, kept = 0;
  for (const [group, urls] of Object.entries(groups)) {
    const q = [...urls]; let bytes = 0;
    await Promise.all(Array.from({ length: 6 }, async () => {
      while (q.length) {
        const src = q.shift(); const rel = mirrorOf(src).slice(MIRROR.length + 1);
        if (!rel) throw new Error("no backup path for " + src);
        const dest = path.join(out, ...rel.split("/"));
        const size = Number((await get(src, "HEAD")).headers.get("content-length"));
        let buf = fs.existsSync(dest) && fs.statSync(dest).size === size ? fs.readFileSync(dest) : null;
        if (buf) kept++;
        else {
          buf = Buffer.from(await (await get(src)).arrayBuffer());
          if (size && buf.length !== size) throw new Error(`${src}: got ${buf.length} bytes, expected ${size}`);
          fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, buf); fetched++;
        }
        bytes += buf.length;
        files[rel] = { source: src, bytes: buf.length, sha256: crypto.createHash("sha256").update(buf).digest("hex") };
      }
    }));
    // The glyph codes in mushaf/madinah.json only fit the exact fonts it was built with.
    const v = group.startsWith("pages-") && group.slice(6);
    if (v && bytes !== fonts[v].bytes) throw new Error(`${group}: ${bytes} bytes, madinah.json was built with ${fonts[v].bytes}; not publishing changed fonts`);
    console.log(`✓ ${group}: ${urls.length} files, ${(bytes / 1048576).toFixed(1)} MB`);
  }
  const sorted = Object.fromEntries(Object.keys(files).sort().map(k => [k, files[k]]));
  fs.writeFileSync(path.join(out, "manifest.json"), JSON.stringify({ built: new Date().toISOString().slice(0, 10), base: MIRROR, files: sorted }, null, 1) + "\n");
  fs.writeFileSync(path.join(out, ".nojekyll"), "");
  fs.writeFileSync(path.join(out, ".gitattributes"), "*.mp3 binary\n*.woff2 binary\n");
  fs.writeFileSync(path.join(out, "README.md"), `# hisn-almuslim-assets

Backup copy of outside files used by [Hisn al-Muslim](https://github.com/hanyarafaosman/hisn-almuslim), served at ${MIRROR}/.
The app uses these only when the original source is unreachable. Every file is an unmodified copy of its source;
\`manifest.json\` lists each file with its source URL, size and SHA-256.

| Folder | Source | Content |
|---|---|---|
| \`hisnmuslim/\` | https://www.hisnmuslim.com | Recorded Hisn al-Muslim adhkar |
| \`qurancdn/\` | https://static.qurancdn.com | King Fahd Complex QCF page fonts (v1: 1405 AH print, v2: 1421 AH print), as served by Quran.com |

Generated by \`scripts/build-mirror.js\` in the app repository; do not edit by hand.
`);
  console.log(`✓ ${Object.keys(files).length} files (${fetched} downloaded, ${kept} unchanged), manifest.json written`);
})().catch(e => { console.error("✗", e.message); process.exit(1); });
